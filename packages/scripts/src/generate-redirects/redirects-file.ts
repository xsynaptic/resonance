import type { RedirectPair } from '#generate-redirects/build-redirect-pairs.ts';

// A placeholder is dynamic just as a splat is, so both sort below the exact rules
export function isDynamic(from: string): boolean {
	return from.includes('*') || from.includes(':');
}

// Cloudflare matches the trailing slash exactly
function toExactRules(from: string, to: string): Array<string> {
	const rule = `${from} ${to} 301`;

	if (from === '/' || !from.endsWith('/')) return [rule];

	return [rule, `${from.slice(0, -1)} ${to} 301`];
}

export function toRedirectsFile(
	structuralRedirects: Array<[string, string]>,
	pairs: Array<RedirectPair>,
): string {
	const structuralExact = structuralRedirects.filter(([from]) => !isDynamic(from));
	const structuralDynamic = structuralRedirects.filter(([from]) => isDynamic(from));

	return [
		'# Generated by `pnpm build`; do not edit',
		'',
		'# Structural moves off WordPress, hand-written in generate-redirects/index.ts',
		...structuralExact.flatMap(([from, to]) => toExactRules(from, to)),
		'',
		'# Generated from `formerIds`',
		...pairs.flatMap(({ from, to }) => toExactRules(from, to)),
		'',
		'# Dynamic rules last: Cloudflare counts every rule below one as dynamic, and allows 100',
		...structuralDynamic.map(([from, to]) => `${from} ${to} 301`),
		'',
	].join('\n');
}
